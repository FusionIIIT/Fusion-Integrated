import { Card, Container, SimpleGrid, Stack, Text } from "@mantine/core";

import { ErrorState } from "../../../ui/components/ErrorState";
import { PageHeader } from "../../../ui/components/PageHeader";
import { usePmsReports } from "../api/hooks";

function Metric({ label, value }: { label: string; value: number }) {
  return (
    <Card padding="md">
      <Text size="xs" c="dimmed" tt="uppercase">{label}</Text>
      <Text fw={700} size="xl">{value}</Text>
    </Card>
  );
}

export default function ReportsPage({ personal = false }: { personal?: boolean }) {
  const report = usePmsReports();
  if (report.error) return <Container size="xl"><ErrorState error={report.error} /></Container>;
  return (
    <Container size="xl">
      <PageHeader title={personal ? "My application report" : "PMS reports and analytics"}
        subtitle="Counts are generated by PMS for the records your current role is authorized to view." />
      {report.isPending ? <Text c="dimmed">Loading report…</Text> : report.data && (
        <Stack gap="md">
          <Metric label="Visible applications" value={report.data.total_applications} />
          <SimpleGrid cols={{ base: 1, md: 2 }}>
            <Card padding="lg">
              <PageHeader title="By status" />
              {Object.entries(report.data.status_distribution).map(([status, count]) => (
                <Text key={status} size="sm">{status.replace(/_/g, " ")} <b>{count}</b></Text>
              ))}
              {!Object.keys(report.data.status_distribution).length && <Text c="dimmed">No status data.</Text>}
            </Card>
            <Card padding="lg">
              <PageHeader title="By technology domain" />
              {Object.entries(report.data.domain_distribution).map(([domain, count]) => (
                <Text key={domain} size="sm">{domain} <b>{count}</b></Text>
              ))}
              {!Object.keys(report.data.domain_distribution).length && <Text c="dimmed">No domain data.</Text>}
            </Card>
          </SimpleGrid>
          <Text size="xs" c="dimmed">
            This API currently provides status and domain aggregates only; trend, workload, and export views are not available.
          </Text>
        </Stack>
      )}
    </Container>
  );
}
