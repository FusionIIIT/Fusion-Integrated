def resolve(rel_path, line):
    full = os.path.join(ROOT, rel_path)
    if not os.path.isfile(full):
        return False, f"file not found: {rel_path}"
    with open(full, encoding="utf-8") as f:
        lines = f.readlines()
    if line < 1 or line > len(lines):
        return False, f"line {line} out of range ({len(lines)} lines) in {rel_path}"
    return True, None


def main():
    errors = []
    rows = []
    for spec_id, rel_path, line, note in LINKS:
        ok, err = resolve(rel_path, line)
        if not ok:
            errors.append((spec_id, err))
        rows.append((spec_id, rel_path, line, note, ok))

    # Write markdown
    os.makedirs(os.path.dirname(DOCS), exist_ok=True)
    with open(DOCS, "w", encoding="utf-8") as f:
        f.write("# LMS Reference\n\n")
        f.write("Auto-generated by `ops/docs/lms_reference.py`. "
                "Each live spec id links to the code that enforces it.\n\n")
        f.write("| Spec id | File | Line | Note |\n")
        f.write("|---|---|---|---|\n")
        for spec_id, rel_path, line, note, ok in rows:
            status = "" if ok else " **BROKEN**"
            f.write(f"| {spec_id} | `{rel_path}` | {line} | {note}{status} |\n")
        if errors:
            f.write("\n## Broken links\n\n")
            for sid, err in errors:
                f.write(f"- {sid}: {err}\n")

    if errors:
        print(f"FAIL: {len(errors)} broken link(s):")
        for sid, err in errors:
            print(f"  {sid}: {err}")
        sys.exit(1)
    print(f"OK: {len(rows)} links resolved.")


if __name__ == "__main__":
    main()
