#!/usr/bin/env python
"""Writes docs/09-gymkhana/gymkhana-reference.md: each live spec id and the code enforcing it."""
from __future__ import annotations

import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]
MODULE = ROOT / "modules" / "gymkhana"
OUT = ROOT / "docs" / "09-gymkhana" / "gymkhana-reference.md"

LIVE = {
    "Requirements": [f"CFR-GYM-{n:03}" for n in range(1, 8)],
    "Atomic requirements": [f"AFR-GYM-{n:03}" for n in range(1, 35)],
    "Use cases": [f"UC-GYM-{n:03}" for n in range(1, 13)],
    "Business rules": [f"BR-GYM-{n:03}" for n in range(1, 22)],
    "Workflows": [f"BW-GYM-{n:02}" for n in range(1, 4)],
}
CITATION = re.compile(r"\b(?:CFR|AFR|UC|BR)-GYM-\d{3}\b|\bBW-GYM-\d{2}\b")


def citations() -> dict[str, list[str]]:
    found: dict[str, list[str]] = {}
    for path in sorted(MODULE.rglob("*.py")):
        if {"tests", "migrations"} & set(path.parts):
            continue
        for number, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
            for spec_id in CITATION.findall(line):
                where = path.relative_to(ROOT).as_posix()
                found.setdefault(spec_id, []).append(f"[{where}:{number}](../../{where}#L{number})")
    return found


def main() -> int:
    found = citations()
    live = {spec_id for ids in LIVE.values() for spec_id in ids}
    missing, unknown = sorted(live - set(found)), sorted(set(found) - live)
    lines = ["# Gymkhana reference", "",
             "Generated by `ops/docs/gymkhana_reference.py`. Do not edit by hand.", ""]
    for title, ids in LIVE.items():
        lines += [f"## {title}", "", "| Id | Enforced at |", "|---|---|"]
        lines += [f"| {i} | {'<br>'.join(found.get(i, ['missing']))} |" for i in ids]
        lines.append("")
    OUT.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    for spec_id in missing:
        print(f"no code cites {spec_id}", file=sys.stderr)
    for spec_id in unknown:
        print(f"{spec_id} is cited but is not a live id", file=sys.stderr)
    return 1 if missing or unknown else 0


if __name__ == "__main__":
    sys.exit(main())
