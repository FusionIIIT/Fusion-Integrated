"""Generate the HR-EIS source-ID reference from the checked traceability register."""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
TRACE = ROOT / "docs" / "10-hreis" / "hr-eis-traceability.md"
OUTPUT = ROOT / "docs" / "10-hreis" / "hreis-reference.md"

TARGETS = {
    "Authorization and row scoping": ("modules/hreis/selectors/scoping.py", "def requests_for"),
    "Employee self-service": ("modules/hreis/services/requests.py", "def create_request"),
    "Employee service records": (
        "modules/hreis/services/requests.py",
        "def maintain_employee_record",
    ),
    "Leave": ("modules/hreis/services/requests.py", "def _validate_request"),
    "Appraisal": ("modules/hreis/services/requests.py", "def _validate_request"),
    "Approval routing": ("modules/hreis/domain/state_machine.py", "TRANSITIONS ="),
    "HR administration": (
        "modules/hreis/services/requests.py",
        "def create_policy_version",
    ),
    "Claim processing": ("modules/hreis/services/requests.py", "def transition_request"),
    "LTC": ("modules/hreis/services/requests.py", "def _validate_request"),
    "CPDA": ("modules/hreis/services/requests.py", "def _validate_request"),
    "Notifications": ("modules/hreis/services/requests.py", "def _write_event"),
    "Audit": ("modules/hreis/models/records.py", "class AuditEvent"),
    "External integration": ("modules/hreis/services/requests.py", "def transition_request"),
    "Payroll/salary scope boundary": ("docs/10-hreis/hr-eis-traceability.md", None),
}


def source_line(relative_path: str, marker: str | None, trace_line: int) -> tuple[str, int]:
    path = ROOT / relative_path
    if not path.is_file():
        raise SystemExit(f"Missing source file: {relative_path}")
    lines = path.read_text().splitlines()
    if marker is None:
        line_number = trace_line
    else:
        line_number = next((index for index, line in enumerate(lines, 1) if marker in line), 0)
    if not 1 <= line_number <= len(lines):
        raise SystemExit(f"Missing source marker {marker!r} in {relative_path}")
    return relative_path, line_number


def generate() -> int:
    rows = []
    trace_lines = TRACE.read_text().splitlines()
    for number, line in enumerate(trace_lines, 1):
        match = re.match(
            r"\| `((?:HR-CFR|HR-AFR|BR-HR|HR-UC)-\d{3}|(?:BW|CW)-HR-\d{2})` \| (.*?) \| (.*?) \|",
            line,
        )
        if not match:
            continue
        identifier, statement, layer = match.groups()
        relative_path, marker = TARGETS[layer]
        target, line_number = source_line(relative_path, marker, number)
        link = f"[`{target}:{line_number}`](../../{target}#L{line_number})"
        rows.append(f"| `{identifier}` | {statement} | {link} |")
    if len(rows) != 193:
        raise SystemExit(f"Expected 193 live source IDs, found {len(rows)}")
    content = [
        "# HR-EIS source reference",
        "",
        (
            "Generated by `ops/docs/hreis_reference.py` from the source traceability register. "
            "A linked implementation seam may be partial; see the status and gap beside each "
            "ID in `hr-eis-traceability.md`."
        ),
        "",
        "| ID | Source statement / goal | Current implementation or gap reference |",
        "|---|---|---|",
        *rows,
        "",
    ]
    OUTPUT.write_text("\n".join(content))
    return len(rows)


if __name__ == "__main__":
    print(f"Wrote {generate()} source links to {OUTPUT.relative_to(ROOT)}")
