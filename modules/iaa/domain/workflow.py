"""Explicit IAA lifecycle transition tables."""
DRAFT="draft";SUBMITTED="submitted";QUERY_RAISED="query_raised";QUERY_RESPONDED="query_responded"
FINANCE_VALIDATED="finance_validated";VERIFIED="verified";APPROVAL_PENDING="approval_pending"
ESCALATED="escalated";ANOMALY_PENDING="anomaly_pending";APPROVED="approved";REJECTED="rejected";RECORDED="recorded"
ANOMALY_OPEN="open";ANOMALY_RESOLVED="resolved";ANOMALY_ESCALATED="escalated"
OBSERVATION_OPEN="open";OBSERVATION_RESPONDED="responded";OBSERVATION_CLOSED="closed"
class InvalidTransition(ValueError):pass
RECORD_TRANSITIONS={DRAFT:{SUBMITTED},SUBMITTED:{QUERY_RAISED,FINANCE_VALIDATED,VERIFIED,APPROVAL_PENDING,ANOMALY_PENDING,REJECTED},
 QUERY_RAISED:{QUERY_RESPONDED},QUERY_RESPONDED:{QUERY_RAISED,FINANCE_VALIDATED,VERIFIED,APPROVAL_PENDING,ANOMALY_PENDING,REJECTED},
 FINANCE_VALIDATED:{APPROVAL_PENDING,APPROVED,VERIFIED,ANOMALY_PENDING,REJECTED},VERIFIED:{RECORDED},
 APPROVAL_PENDING:{APPROVAL_PENDING,APPROVED,REJECTED,ESCALATED},ESCALATED:{APPROVAL_PENDING,APPROVED,REJECTED},
 ANOMALY_PENDING:{SUBMITTED,REJECTED},APPROVED:{RECORDED},REJECTED:set(),RECORDED:set()}
ANOMALY_TRANSITIONS={ANOMALY_OPEN:{ANOMALY_RESOLVED,ANOMALY_ESCALATED},ANOMALY_ESCALATED:{ANOMALY_RESOLVED},ANOMALY_RESOLVED:set()}
OBSERVATION_TRANSITIONS={OBSERVATION_OPEN:{OBSERVATION_RESPONDED},OBSERVATION_RESPONDED:{OBSERVATION_OPEN,OBSERVATION_CLOSED},OBSERVATION_CLOSED:set()}
def _assert(table,b,a):
 if a not in table.get(b,set()):raise InvalidTransition(f"Illegal transition: {b!r} -> {a!r}.")
def assert_record_transition(b,a):_assert(RECORD_TRANSITIONS,b,a)
def assert_anomaly_transition(b,a):_assert(ANOMALY_TRANSITIONS,b,a)
def assert_observation_transition(b,a):_assert(OBSERVATION_TRANSITIONS,b,a)
