"""LMS Course Workspace URL routes."""
from django.urls import path

from modules.lms.api.views import (
    CourseAnnouncementDetailView,
    CourseAnnouncementListView,
    CourseAssignmentDeadlineView,
    CourseAssignmentDetailView,
    CourseAssignmentDownloadView,
    CourseAssignmentExtensionDetailView,
    CourseAssignmentExtensionsView,
    CourseAssignmentListView,
    CourseAssignmentWindowView,
    CourseListView,
    CourseMaterialDetailView,
    CourseMaterialDownloadView,
    CourseMaterialListView,
    CourseWorkspaceDetailView,
)

urlpatterns = [
    path("courses", CourseListView.as_view(), name="course-list"),
    path(
        "courses/<str:code>",
        CourseWorkspaceDetailView.as_view(),
        name="course-workspace-detail",
    ),
    path(
        "courses/<str:code>/materials",
        CourseMaterialListView.as_view(),
        name="course-material-list",
    ),
    path(
        "courses/<str:code>/materials/<int:material_id>",
        CourseMaterialDetailView.as_view(),
        name="course-material-detail",
    ),
    path(
        "courses/<str:code>/materials/<int:material_id>/download",
        CourseMaterialDownloadView.as_view(),
        name="course-material-download",
    ),
    path(
        "courses/<str:code>/announcements",
        CourseAnnouncementListView.as_view(),
        name="course-announcement-list",
    ),
    path(
        "courses/<str:code>/announcements/<int:announcement_id>",
        CourseAnnouncementDetailView.as_view(),
        name="course-announcement-detail",
    ),
    path(
        "courses/<str:code>/assignments",
        CourseAssignmentListView.as_view(),
        name="course-assignment-list",
    ),
    path(
        "courses/<str:code>/assignments/<int:assignment_id>",
        CourseAssignmentDetailView.as_view(),
        name="course-assignment-detail",
    ),
    path(
        "courses/<str:code>/assignments/<int:assignment_id>/download",
        CourseAssignmentDownloadView.as_view(),
        name="course-assignment-download",
    ),
    path(
        "courses/<str:code>/assignments/<int:assignment_id>/deadline",
        CourseAssignmentDeadlineView.as_view(),
        name="course-assignment-deadline",
    ),
    path(
        "courses/<str:code>/assignments/<int:assignment_id>/window",
        CourseAssignmentWindowView.as_view(),
        name="course-assignment-window",
    ),
    path(
        "courses/<str:code>/assignments/<int:assignment_id>/extensions",
        CourseAssignmentExtensionsView.as_view(),
        name="course-assignment-extensions",
    ),
    path(
        "courses/<str:code>/assignments/<int:assignment_id>/extensions/<int:extension_id>",
        CourseAssignmentExtensionDetailView.as_view(),
        name="course-assignment-extension-detail",
    ),
]
