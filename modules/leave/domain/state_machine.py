_withdrawable_leave_states = [
    DRAFT, AWAITING_SUBSTITUTE, APPLICANT_ACTION_REQUIRED, AWAITING_UNIT_HEAD,
    AWAITING_ESTABLISHMENT, AWAITING_FINAL_SANCTION, AWAITING_DIRECTOR_SANCTION,
]
for _state in _withdrawable_leave_states:
    _rows.append((_state, ACTION_WITHDRAW, ACTOR_EMPLOYEE, WITHDRAWN))

_withdrawable_extension_states = [
    EXTENSION_AWAITING_SUBSTITUTE, EXTENSION_APPLICANT_ACTION_REQUIRED,
    EXTENSION_AWAITING_UNIT_HEAD, EXTENSION_PENDING_ESTABLISHMENT,
    EXTENSION_PENDING_FINAL,
]
for _state in _withdrawable_extension_states:
    _rows.append((_state, ACTION_WITHDRAW, ACTOR_EMPLOYEE, EXTENSION_WITHDRAWN))

for _actor in (ACTOR_ESTABLISHMENT, ACTOR_LEAVE_ADMIN):
    _rows.append((RESUMPTION_PENDING, ACTION_RESUME_NORMAL, _actor, RESUMPTION_NORMAL))
    _rows.append((RESUMPTION_PENDING, ACTION_RESUME_EARLY, _actor, RESUMPTION_EARLY))
    _rows.append((RESUMPTION_PENDING, ACTION_RESUME_LATE, _actor, RESUMPTION_LATE))

TRANSITIONS = {}
for _from, _action, _actor, _to in _rows:
    _key = (_from, _action, _actor)
    if _key in TRANSITIONS:
        raise ValueError("duplicate transition key: " + str(_key))
    TRANSITIONS[_key] = _to

TERMINAL_STATES = {
    REJECTED, WITHDRAWN, CANCELLED, CANCELLATION_REJECTED,
    EXTENSION_APPROVED, EXTENSION_REJECTED, EXTENSION_WITHDRAWN,
    RESUMPTION_NORMAL, RESUMPTION_EARLY, RESUMPTION_LATE,
}


def get_next_state(current_state, action, actor_kind):
    key = (current_state, action, actor_kind)
    if key not in TRANSITIONS:
        raise TransitionException(
            "Invalid transition: " + str(current_state) + " --" + action + "(" + actor_kind + ")"
        )
    return TRANSITIONS[key]


def is_terminal(state):
    return state in TERMINAL_STATES