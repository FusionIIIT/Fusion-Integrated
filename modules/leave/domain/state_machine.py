class TransitionException(Exception):
    """Raised when a state transition is invalid."""
    pass


class StateMachine:
    """
    Declarative state machine implementing all 17 Basis Workflows (BW-EL-01..17)
    and 4 Composite Workflows (CW-EL-01..04).
    """
    
    # New Leave Composite Workflow (CW-EL-01)
    NEW_LEAVE_TRANSITIONS: Dict[Tuple, str] = {
        # DRAFT -> AWAITING_SUBSTITUTE (if coverage required)
        (DRAFT, ACTION_SUBSTITUTE_RESPONSE, ACTOR_EMPLOYEE): AWAITING_SUBSTITUTE,
        
        # DRAFT -> AWAITING_UNIT_HEAD (if no substitute required)
        (DRAFT, ACTION_UNIT_HEAD_DECISION, ACTOR_EMPLOYEE): AWAITING_UNIT_HEAD,
        
        # DRAFT -> AWAITING_DIRECTOR_SANCTION (for Director's leave)
        (DRAFT, ACTION_DIRECTOR_SANCTION, ACTOR_EMPLOYEE): AWAITING_DIRECTOR_SANCTION,
        
        # AWAITING_SUBSTITUTE -> AWAITING_UNIT_HEAD (substitute accepted)
        (AWAITING_SUBSTITUTE, ACTION_SUBSTITUTE_RESPONSE, ACTOR_SUBSTITUTE): AWAITING_UNIT_HEAD,
        
        # AWAITING_SUBSTITUTE -> APPLICANT_ACTION_REQUIRED (substitute declined)
        (AWAITING_SUBSTITUTE, ACTION_SUBSTITUTE_RESPONSE, ACTOR_SUBSTITUTE): APPLICANT_ACTION_REQUIRED,
        
        # AWAITING_SUBSTITUTE -> DRAFT (substitute nominated but no response yet)
        (AWAITING_SUBSTITUTE, ACTION_SUBSTITUTE_RESPONSE, ACTOR_SUBSTITUTE): DRAFT,
        
        # APPLICANT_ACTION_REQUIRED -> AWAITING_UNIT_HEAD (applicant resubmits)
        (APPLICANT_ACTION_REQUIRED, ACTION_RESUBMIT, ACTOR_EMPLOYEE): AWAITING_UNIT_HEAD,
        
        # AWAITING_UNIT_HEAD -> APPROVED (Unit Head approves CL/RH)
        (AWAITING_UNIT_HEAD, ACTION_UNIT_HEAD_DECISION, ACTOR_UNIT_HEAD): APPROVED,
        
        # AWAITING_UNIT_HEAD -> REJECTED (Unit Head rejects)
        (AWAITING_UNIT_HEAD, ACTION_UNIT_HEAD_DECISION, ACTOR_UNIT_HEAD): REJECTED,
        
        # AWAITING_UNIT_HEAD -> AWAITING_ESTABLISHMENT (higher sanction required)
        (AWAITING_UNIT_HEAD, ACTION_ESTABLISHMENT_ACTION, ACTOR_UNIT_HEAD): AWAITING_ESTABLISHMENT,
        
        # AWAITING_UNIT_HEAD -> AWAITING_FINAL_SANCTION (Dean/Registrar level)
        (AWAITING_UNIT_HEAD, ACTION_ESTABLISHMENT_ACTION, ACTOR_UNIT_HEAD): AWAITING_FINAL_SANCTION,
        
        # AWAITING_FINAL_SANCTION -> AWAITING_DIRECTOR_SANCTION (Director level)
        (AWAITING_FINAL_SANCTION, ACTION_DIRECTOR_SANCTION, ACTOR_ESTABLISHMENT): AWAITING_DIRECTOR_SANCTION,
        
        # AWAITING_DIRECTOR_SANCTION -> APPROVED (Director approves)
        (AWAITING_DIRECTOR_SANCTION, ACTION_DIRECTOR_SANCTION, ACTOR_DIRECTOR): APPROVED,
        
        # AWAITING_DIRECTOR_SANCTION -> REJECTED (Director rejects)
        (AWAITING_DIRECTOR_SANCTION, ACTION_UNIT_HEAD_DECISION, ACTOR_DIRECTOR): REJECTED,
        
        # AWAITING_ESTABLISHMENT -> APPROVED
        (AWAITING_ESTABLISHMENT, ACTION_ESTABLISHMENT_ACTION, ACTOR_ESTABLISHMENT): APPROVED,
        
        # AWAITING_ESTABLISHMENT -> REJECTED
        (AWAITING_ESTABLISHMENT, ACTION_ESTABLISHMENT_ACTION, ACTOR_ESTABLISHMENT): REJECTED,
        
        # AWAITING_ESTABLISHMENT -> AWAITING_DIRECTOR_SANCTION
        (AWAITING_ESTABLISHMENT, ACTION_DIRECTOR_SANCTION, ACTOR_ESTABLISHMENT): AWAITING_DIRECTOR_SANCTION,
    }
    
    # Terminal Withdrawn Transitions (BR-EL-022, BR-EL-034)
    # Can withdraw from any pending state
    WITHDRAWN_TRANSITIONS: Dict[Tuple, str] = {
        (DRAFT, ACTION_WITHDRAW, ACTOR_EMPLOYEE): WITHDRAWN,
        (AWAITING_SUBSTITUTE, ACTION_WITHDRAW, ACTOR_EMPLOYEE): WITHDRAWN,
        (APPLICANT_ACTION_REQUIRED, ACTION_WITHDRAW, ACTOR_EMPLOYEE): WITHDRAWN,
        (AWAITING_UNIT_HEAD, ACTION_WITHDRAW, ACTOR_EMPLOYEE): WITHDRAWN,
        (AWAITING_ESTABLISHMENT, ACTION_WITHDRAW, ACTOR_EMPLOYEE): WITHDRAWN,
        (AWAITING_FINAL_SANCTION, ACTION_WITHDRAW, ACTOR_EMPLOYEE): WITHDRAWN,
        (AWAITING_DIRECTOR_SANCTION, ACTION_WITHDRAW, ACTOR_EMPLOYEE): WITHDRAWN,
        (APPROVED, ACTION_WITHDRAW, ACTOR_EMPLOYEE): WITHDRAWN,
    }
    
    # Cancellation Composite Workflow (CW-EL-02)
    CANCELLATION_TRANSITIONS: Dict[Tuple, str] = {
        # CANCELLATION_PENDING_UNIT_HEAD -> CANCELLATION_PENDING_ESTABLISHMENT
        (CANCELLATION_PENDING_UNIT_HEAD, ACTION_ESTABLISHMENT_ACTION, ACTOR_UNIT_HEAD): CANCELLATION_PENDING_ESTABLISHMENT,
        
        # CANCELLATION_PENDING_ESTABLISHMENT -> CANCELLATION_PENDING_FINAL
        (CANCELLATION_PENDING_ESTABLISHMENT, ACTION_ESTABLISHMENT_ACTION, ACTOR_ESTABLISHMENT): CANCELLATION_PENDING_FINAL,
        
        # CANCELLATION_PENDING_FINAL -> CANCELLED
        (CANCELLATION_PENDING_FINAL, ACTION_DIRECTOR_SANCTION, ACTOR_DIRECTOR): CANCELLED,
        
        # CANCELLATION_PENDING_FINAL -> CANCELLATION_REJECTED
        (CANCELLATION_PENDING_FINAL, ACTION_ESTABLISHMENT_ACTION, ACTOR_DIRECTOR): CANCELLATION_REJECTED,
        
        # Any cancellation state -> CANCELLATION_REJECTED
        (CANCELLATION_PENDING_UNIT_HEAD, ACTION_ESTABLISHMENT_ACTION, ACTOR_DIRECTOR): CANCELLATION_REJECTED,
        (CANCELLATION_PENDING_ESTABLISHMENT, ACTION_ESTABLISHMENT_ACTION, ACTOR_DIRECTOR): CANCELLATION_REJECTED,
        
        # CANCELLED is terminal
        (CANCELLED, ACTION_WITHDRAW, ACTOR_EMPLOYEE): CANCELLED,
    }
    
    # Extension Composite Workflow (CW-EL-03)
    EXTENSION_TRANSITIONS: Dict[Tuple, str] = {
        # EXTENSION_AWAITING_SUBSTITUTE -> EXTENSION_APPLICANT_ACTION_REQUIRED
        (EXTENSION_AWAITING_SUBSTITUTE, ACTION_SUBSTITUTE_RESPONSE, ACTOR_SUBSTITUTE): EXTENSION_APPLICANT_ACTION_REQUIRED,
        
        # EXTENSION_APPLICANT_ACTION_REQUIRED -> EXTENSION_AWAITING_UNIT_HEAD
        (EXTENSION_APPLICANT_ACTION_REQUIRED, ACTION_RESUBMIT, ACTOR_EMPLOYEE): EXTENSION_AWAITING_UNIT_HEAD,
        
        # EXTENSION_AWAITING_UNIT_HEAD -> EXTENSION_PENDING_ESTABLISHMENT
        (EXTENSION_AWAITING_UNIT_HEAD, ACTION_ESTABLISHMENT_ACTION, ACTOR_UNIT_HEAD): EXTENSION_PENDING_ESTABLISHMENT,
        
        # EXTENSION_PENDING_ESTABLISHMENT -> EXTENSION_PENDING_FINAL
        (EXTENSION_PENDING_ESTABLISHMENT, ACTION_ESTABLISHMENT_ACTION, ACTOR_ESTABLISHMENT): EXTENSION_PENDING_FINAL,
        
        # EXTENSION_PENDING_FINAL -> EXTENSION_APPROVED
        (EXTENSION_PENDING_FINAL, ACTION_DIRECTOR_SANCTION, ACTOR_DIRECTOR): EXTENSION_APPROVED,
        
        # EXTENSION_PENDING_FINAL -> EXTENSION_REJECTED
        (EXTENSION_PENDING_FINAL, ACTION_ESTABLISHMENT_ACTION, ACTOR_DIRECTOR): EXTENSION_REJECTED,
        
        # EXTENSION_PENDING_FINAL -> EXTENSION_WITHDRAWN
        (EXTENSION_PENDING_FINAL, ACTION_WITHDRAW, ACTOR_EMPLOYEE): EXTENSION_WITHDRAWN,
        
        # EXTENSION_AWAITING_UNIT_HEAD -> EXTENSION_REJECTED
        (EXTENSION_AWAITING_UNIT_HEAD, ACTION_ESTABLISHMENT_ACTION, ACTOR_DIRECTOR): EXTENSION_REJECTED,
        
        # EXTENSION_AWAITING_UNIT_HEAD -> EXTENSION_WITHDRAWN
        (EXTENSION_AWAITING_UNIT_HEAD, ACTION_WITHDRAW, ACTOR_EMPLOYEE): EXTENSION_WITHDRAWN,
        
        # EXTENSION_PENDING_ESTABLISHMENT -> EXTENSION_WITHDRAWN
        (EXTENSION_PENDING_ESTABLISHMENT, ACTION_WITHDRAW, ACTOR_EMPLOYEE): EXTENSION_WITHDRAWN,
        
        # EXTENSION_PENDING_FINAL -> EXTENSION_WITHDRAWN
        (EXTENSION_PENDING_FINAL, ACTION_WITHDRAW, ACTOR_EMPLOYEE): EXTENSION_WITHDRAWN,
    }
    
    # Resumption Composite Workflow (CW-EL-04)
    RESUMPTION_TRANSITIONS: Dict[Tuple, str] = {
        # RESUMPTION_PENDING -> RESUMPTION_NORMAL
        (RESUMPTION_PENDING, ACTION_RESUME, ACTOR_EMPLOYEE): RESUMPTION_NORMAL,
        
        # RESUMPTION_PENDING -> RESUMPTION_EARLY
        (RESUMPTION_PENDING, ACTION_RESUME, ACTOR_EMPLOYEE): RESUMPTION_EARLY,
        
        # RESUMPTION_PENDING -> RESUMPTION_LATE
        (RESUMPTION_PENDING, ACTION_RESUME, ACTOR_EMPLOYEE): RESUMPTION_LATE,
    }
    
    # Combine all transitions
    ALL_TRANSITIONS: Dict[Tuple, str] = {
        **NEW_LEAVE_TRANSITIONS,
        **WITHDRAWN_TRANSITIONS,
        **CANCELLATION_TRANSITIONS,
        **EXTENSION_TRANSITIONS,
        **RESUMPTION_TRANSITIONS,
    }
    
    # Terminal states where no further transitions are allowed
    TERMINAL_STATES: set = {
        WITHDRAWN, CANCELLED, APPROVED, REJECTED,
        EXTENSION_APPROVED, EXTENSION_REJECTED, EXTENSION_WITHDRAWN
    }
    
    @classmethod
    def get_next_state(cls, current_state: str, action: str, actor_kind: str) -> str:
        """
        Get the next state given current state, action, and actor.
        
        Args:
            current_state: Current leave request state
            action: Action being performed
            actor_kind: Actor performing the action
            
        Returns:
            Next state string
            
        Raises:
            TransitionException: If the transition is invalid
        """
        key = (current_state, action, actor_kind)
        
        if key in cls.ALL_TRANSITIONS:
            return cls.ALL_TRANSITIONS[key]
        
        raise TransitionException(
            f"Invalid transition: {current_state} --{action}({actor_kind})--> ?"
        )
    
    @classmethod
    def is_terminal(cls, state: str) -> bool:
        """Check if a state is terminal."""
        return state in cls.TERMINAL_STATES


