from decimal import Decimal
from django.db import transaction
from django.utils import timezone
from modules.elm.domain.policy import validate_application_bounds
from modules.elm.models import LeaveApplication, LeaveBalance, LeaveType, SubstituteNomination


class LeaveApplicationError(Exception):
    pass


@transaction.atomic
def submit_leave_application(
    applicant_id: int,
    leave_type_code: str,
    start_date,
    end_date,
    number_of_days: Decimal,
    purpose: str,
    station_leave: bool = False,
    substitute_id: int | None = None,
    substitute_duties: str = "",
) -> LeaveApplication:
    """Validate and persist a leave request."""
    try:
        leave_type = LeaveType.objects.get(code=leave_type_code)
    except LeaveType.DoesNotExist:
        raise LeaveApplicationError(f"Leave type '{leave_type_code}' does not exist.")

    current_year = start_date.year
    balance = LeaveBalance.objects.filter(
        user_id=applicant_id,
        leave_type=leave_type,
        year=current_year,
    ).first()

    available = balance.remaining if balance else Decimal("0.0")
    is_valid, reason = validate_application_bounds(leave_type_code, number_of_days, available)
    if not is_valid:
        raise LeaveApplicationError(reason)

    initial_status = "SUBSTITUTE_PENDING" if substitute_id else "SUBMITTED"

    application = LeaveApplication.objects.create(
        applicant_id=applicant_id,
        leave_type=leave_type,
        start_date=start_date,
        end_date=end_date,
        number_of_days=number_of_days,
        purpose=purpose,
        station_leave=station_leave,
        status=initial_status,
    )

    if substitute_id:
        SubstituteNomination.objects.create(
            application=application,
            substitute_id=substitute_id,
            duties_description=substitute_duties,
        )

    return application


@transaction.atomic
def record_substitute_response(
    nomination_id: int,
    substitute_id: int,
    accepted: bool,
) -> SubstituteNomination:
    """Record consent from the nominated substitute."""
    nomination = SubstituteNomination.objects.select_related("application").get(id=nomination_id)
    if nomination.substitute_id != substitute_id:
        raise LeaveApplicationError("Unauthorized to respond for this substitute nomination.")

    nomination.accepted = accepted
    nomination.response_date = timezone.now()
    nomination.save(update_fields=["accepted", "response_date"])

    app = nomination.application
    if accepted:
        app.status = "SUBMITTED"
    else:
        app.status = "REJECTED"
        app.remarks = f"Substitute nomination declined by user {substitute_id}."
    app.save(update_fields=["status", "remarks"])

    return nomination


@transaction.atomic
def withdraw_application(application_id: int, user_id: int) -> LeaveApplication:
    """Withdraw a leave application before final sanction."""
    app = LeaveApplication.objects.get(id=application_id, applicant_id=user_id)
    if app.status in ("APPROVED", "WITHDRAWN"):
        raise LeaveApplicationError(f"Cannot withdraw application in status {app.status}.")

    app.status = "WITHDRAWN"
    app.save(update_fields=["status"])
    return app
