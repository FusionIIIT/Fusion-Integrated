class LeaveRuleError(Exception):
    """Base class for leave rule violations."""


class InvalidLeaveRange(LeaveRuleError): ...
class NoBalanceRecord(LeaveRuleError): ...
class InsufficientBalance(LeaveRuleError): ...
class SelfReviewNotAllowed(LeaveRuleError): ...
class NotPending(LeaveRuleError): ...
class ApplicationNotFound(LeaveRuleError): ...
