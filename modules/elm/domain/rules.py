from __future__ import annotations

from datetime import date


def overlaps(
    a_start: date, a_end: date, a_half: str,
    b_start: date, b_end: date, b_half: str,
) -> bool:
    """BR-EL-012: a new request must not overlap an existing pending/approved
    one, except first-half/second-half CL on the same single date."""
    if (
        a_start == b_start == a_end == b_end
        and (
            (a_half == "first_half" and b_half == "second_half")
            or (a_half == "second_half" and b_half == "first_half")
        )
    ):
        return False
    return not (b_end < a_start or b_start > a_end)


def validate_substitute(
    applicant_user_id: int,
    substitute_user_id: int | None,
    substitute_is_known_employee: bool,
    substitute_has_conflicting_leave: bool,
) -> tuple[bool, str]:
    """BR-EL-014: substitute must be another real employee with no
    overlapping pending/approved leave during the responsibility period."""
    if substitute_user_id is None:
        return True, "not required"
    if substitute_user_id == applicant_user_id:
        return False, "substitute cannot be the applicant"
    if not substitute_is_known_employee:
        return False, "substitute must be an existing employee"
    if substitute_has_conflicting_leave:
        return False, "substitute has overlapping pending or approved leave"
    return True, "eligible"


def can_withdraw(status: str) -> bool:
    """BR-EL-022 / BR-EL-034: withdrawable only while still pending, i.e.
    before any final Unit-Head (CL/RH) decision."""
    return status == "pending"


def can_cancel(status: str, start_date: date, today: date) -> bool:
    """BR-EL-023: an approved leave may be cancelled only before it starts."""
    return status == "approved" and today < start_date
